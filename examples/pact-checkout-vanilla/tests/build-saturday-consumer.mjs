import {createRequire} from 'node:module';
import {mkdir,realpath,stat} from 'node:fs/promises';
import path from 'node:path';
const require=createRequire(path.resolve('packages/pact-sdk/package.json'));
const {build}=require('esbuild');
if(!process.env.PACT_EXTERNAL_SATURDAY)throw Error('Set PACT_EXTERNAL_SATURDAY explicitly for this optional external-consumer check.');
const external=await realpath(path.resolve(process.env.PACT_EXTERNAL_SATURDAY));
const entry=path.join(external,'worker/pact-license.js');
if(!(await stat(entry)).isFile())throw Error('External consumer entry is not a file.');
const output=path.resolve('web/test-results/checkout-saturday-consumer');await mkdir(output,{recursive:true});
await build({entryPoints:[entry],bundle:true,format:'esm',platform:'browser',target:'es2022',outfile:path.join(output,'saturday.mjs'),alias:{'@pact/sdk':path.resolve('packages/pact-sdk/dist/index.js')}});
console.log('Original Saturday worker bundled read-only against compiled @pact/sdk root export into PACT ignored consumer.');
